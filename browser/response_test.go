package browser_test

import (
	"bytes"
	"encoding/json"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
	"time"

	"github.com/Tangerg/frame/browser"
	framehost "github.com/Tangerg/frame/host"
	"github.com/Tangerg/frame/value"
)

func TestControlResponsesMatchGeneratedSDK(t *testing.T) {
	e := openBridge(t, filepath.Join(t.TempDir(), "state.sqlite"), true)
	var samples []struct {
		Method string          `json:"method"`
		Body   json.RawMessage `json:"body"`
	}
	capture := func(method string, input any) json.RawMessage {
		t.Helper()
		response := controlReply(t, e.bridge, e.credentials.Token, method, input)
		if response.Code != http.StatusOK {
			t.Fatalf("%s: %d %s", method, response.Code, response.Body.String())
		}
		sample := struct {
			Method string          `json:"method"`
			Body   json.RawMessage `json:"body"`
		}{Method: method, Body: bytes.Clone(response.Body.Bytes())}
		samples = append(samples, sample)
		return sample.Body
	}
	plan, activated := e.beginActivation("component")
	capture("poll", struct{}{})
	capture("admitPlan", plan)
	capture("ready", e.readyReport(plan))
	if err := <-activated; err != nil {
		t.Fatal(err)
	}
	capture("poll", struct{}{})
	var snapshot browser.Snapshot
	if err := json.Unmarshal(capture("snapshot", snapshotRequest(e.first.Ref().Name)), &snapshot); err != nil {
		t.Fatal(err)
	}
	capture("closeSnapshot", snapshot.ID)
	request := e.selectionRequest(plan, "acquire")
	var grant browser.UseGrant
	if err := json.Unmarshal(capture("acquire", request), &grant); err != nil {
		t.Fatal(err)
	}
	capture("validateUse", grant)
	publicationRequest := browser.PublicationRequest{OperationID: "dynamic", Authority: plan.Authority, Realm: plan.Realm, Execution: plan.Execution, Object: browser.ObjectRef{ObjectID: "dynamic-object", Export: browser.LocalExport{InstanceID: plan.Units[0].Instance.ID, Name: "dynamic", Contract: e.first.Ref()}}, MetadataJSON: `{"label":"dynamic"}`}
	var publication browser.PublicationResult
	if err := json.Unmarshal(capture("publish", publicationRequest), &publication); err != nil {
		t.Fatal(err)
	}
	capture("publication", publicationRequest.OperationID)
	capture("withdraw", browser.Withdrawal{Authority: plan.Authority, PublicationID: publication.Publication.ID})
	capture("prove", useProof(plan, grant))
	capture("reconnect", browser.ReconnectRequest{Authority: plan.Authority, Realm: plan.Realm, Executions: []browser.Execution{plan.Execution}})

	var err error
	e.plugin, err = framehost.Define(framehost.Definition{Revision: value.Hash([]byte("no-export-unit")), Units: []framehost.Unit{{Declaration: framehost.UnitDeclaration{ID: "view", Profile: framehost.BrowserJS}}}})
	if err != nil {
		t.Fatal(err)
	}
	activated = beginBrowserActivation(e, "no-exports")
	for {
		projection, err := e.bridge.Poll(e.ctx, e.credentials.Token)
		if err != nil {
			t.Fatal(err)
		}
		if len(projection.Plans) > 0 {
			plan = projection.Plans[0]
			break
		}
		select {
		case err := <-activated:
			t.Fatalf("activation ended before plan: %v", err)
		case <-e.ctx.Done():
			t.Fatal(e.ctx.Err())
		case <-time.After(time.Millisecond):
		}
	}
	var received browser.Poll
	if err := json.Unmarshal(capture("poll", struct{}{}), &received); err != nil {
		t.Fatal(err)
	}
	plan = received.Plans[0]
	e.admit(plan)
	capture("admitPlan", plan)
	capture("ready", e.readyReport(plan))
	if err := <-activated; err != nil {
		t.Fatal(err)
	}

	var generated bytes.Buffer
	if err := browser.WriteTypeScript(&generated); err != nil {
		t.Fatal(err)
	}
	module := filepath.Join(t.TempDir(), "protocol.generated.ts")
	if err := os.WriteFile(module, generated.Bytes(), 0600); err != nil {
		t.Fatal(err)
	}
	input, err := json.Marshal(samples)
	if err != nil {
		t.Fatal(err)
	}
	command := exec.CommandContext(t.Context(), "node", "--input-type=module", "-e", `
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
const { decodeControlOutput } = await import(pathToFileURL(process.argv[1]));
for (const { method, body } of JSON.parse(readFileSync(0, "utf8")))
  assert.doesNotThrow(() => decodeControlOutput(method, body), method + ": " + JSON.stringify(body));
`, module)
	command.Stdin = bytes.NewReader(input)
	if output, err := command.CombinedOutput(); err != nil {
		t.Fatalf("actual Handler replies failed SDK admission: %s\n%v", output, err)
	}
}
