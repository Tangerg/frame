package contractgen

import (
	"encoding/hex"
	json "encoding/json/v2"
	"errors"
	"fmt"
	"go/format"
	"go/token"
	"maps"
	"slices"
	"strconv"
	"strings"
	"unicode"

	framevalue "github.com/Tangerg/frame/value"
)

type featureGoOptions struct{ Package, Prefix string }

const goValueImport = "framevalue"

type goStringEnum struct {
	values   []string
	position typePosition
}

type featureGo struct {
	symbols    *symbolTable
	names      map[*projectionNode]string
	enums      map[string]goStringEnum
	methods    map[string]string
	capability string
	usesValue  bool
}

// Go types are projections of the same admitted schemas as TS. Constraints stay
// in the canonical descriptor; callers validate it before decoding typed output.
func (f *featureArtifacts) goProjection(output featureGoOptions) ([]byte, error) {
	if output.Package == "_" || !token.IsIdentifier(output.Package) {
		return nil, fmt.Errorf("%w: Go package must be a non-blank identifier", ErrInvalid)
	}
	if output.Prefix != "" && (!token.IsIdentifier(output.Prefix) || !unicode.IsUpper([]rune(output.Prefix)[0])) {
		return nil, fmt.Errorf("%w: Go prefix must be an exported identifier", ErrInvalid)
	}
	emitter, err := f.goNames(output.Prefix)
	if err != nil {
		return nil, err
	}
	var body strings.Builder
	for _, name := range slices.Sorted(maps.Keys(f.projection.definitions)) {
		node := f.projection.definitions[name]
		if node.pureReference() {
			continue
		}
		projectedName := emitter.names[node]
		value, err := emitter.typ(node, projectedName, definitionPosition)
		if err != nil {
			return nil, fmt.Errorf("feature Go %s: %w", name, err)
		}
		fmt.Fprintf(&body, "type %s %s\n\n", projectedName, value)
	}
	descriptor, err := json.Marshal(f.capability.Descriptor(), json.Deterministic(true))
	if err != nil {
		return nil, err
	}
	fmt.Fprintf(&body, "const %s = %s\n\n", emitter.capability, strconv.Quote(string(descriptor)))
	for _, method := range f.methods {
		fmt.Fprintf(&body, "const %s = %s\n", emitter.methods[method.Name], strconv.Quote(method.Name))
		body.WriteString("\n")
	}
	var result strings.Builder
	fmt.Fprintf(&result, "// Code generated by Frame contractgen from the published capability descriptor. DO NOT EDIT.\npackage %s\n\n", output.Package)
	if emitter.usesValue {
		fmt.Fprintf(&result, "import %s \"github.com/Tangerg/frame/value\"\n\n", goValueImport)
	}
	for _, name := range slices.Sorted(maps.Keys(emitter.enums)) {
		enum := emitter.enums[name]
		if enum.position == inlinePosition {
			fmt.Fprintf(&result, "type %s string\n\n", name)
		}
		result.WriteString("const (\n")
		var members []string
		for _, value := range enum.values {
			constant := emitter.symbols.claim(name + goFeatureIdentifier(value))
			fmt.Fprintf(&result, "%s %s = %s\n", constant, name, strconv.Quote(value))
			members = append(members, "string("+constant+")")
		}
		result.WriteString(")\n\n")
		fmt.Fprintf(&result, "func (%s) JSONSchemaEnum() []string { return []string{%s} }\n\n", name, strings.Join(members, ","))
	}
	result.WriteString(body.String())
	return format.Source([]byte(result.String()))
}

func goFeatureIdentifier(value string) string {
	var out strings.Builder
	upper := true
	for _, r := range value {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		out.WriteRune(r)
	}
	name := out.String()
	if !token.IsIdentifier(name) {
		return "Value" + strings.ToUpper(hex.EncodeToString([]byte(value)))
	}
	if !unicode.IsUpper([]rune(name)[0]) {
		return "Value" + name
	}
	return name
}

// Named numeric and opaque projections need struct wrappers to retain their codecs.
type typePosition uint8

const (
	inlinePosition typePosition = iota
	definitionPosition
)

func (e *featureGo) typ(node *projectionNode, path string, position typePosition) (string, error) {
	if node == nil {
		return e.opaque(position), nil
	}
	if position == inlinePosition && e.names[node] != "" {
		return e.namedType(node)
	}
	if node.pureReference() {
		return e.namedType(node.reference)
	}
	if len(node.kinds) > 0 {
		return e.opaque(position), nil
	}
	switch node.kind {
	case framevalue.TypeBoolean:
		return "bool", nil
	case framevalue.TypeInteger, framevalue.TypeNumber:
		return e.number(position), nil
	case framevalue.TypeString:
		return e.stringType(node, path, position), nil
	case framevalue.TypeArray:
		value, err := e.typ(node.items, path+"Item", inlinePosition)
		return "[]" + value, err
	case framevalue.TypeObject:
		return e.objectType(node, path)
	default:
		return e.opaque(position), nil
	}
}

// A shared object node may close a structural recursion; its pointer preserves
// that schema without creating an illegal recursive Go value.
func (e *featureGo) namedType(node *projectionNode) (string, error) {
	seen := make(map[*projectionNode]bool)
	for node.pureReference() {
		if seen[node] {
			return "", fmt.Errorf("feature Go reference cycle at %s", node.referencePath)
		}
		seen[node] = true
		node = node.reference
	}
	name := e.names[node]
	if name == "" {
		return "", errors.New("feature Go unresolved schema reference")
	}
	if goStruct(node) {
		name = "*" + name
	}
	return name, nil
}

func (e *featureGo) stringType(node *projectionNode, path string, position typePosition) string {
	values := node.stringValues
	if len(values) == 0 {
		return "string"
	}
	if position == inlinePosition {
		path = e.symbols.claim(path)
	}
	e.enums[path] = goStringEnum{values: values, position: position}
	if position == definitionPosition {
		return "string"
	}
	return path
}

// objectType is a struct for a closed object with representable members,
// otherwise a map that keeps every admitted member.
func (e *featureGo) objectType(node *projectionNode, path string) (string, error) {
	object := node.object
	if !goStruct(node) {
		if len(object.properties) == 0 && object.openness == objectTyped && !object.patterns {
			value, err := e.typ(object.additional, path+"Value", inlinePosition)
			return "map[string]" + value, err
		}
		e.usesValue = true
		return "map[string]" + goValueImport + ".JSON", nil
	}
	var out strings.Builder
	out.WriteString("struct {\n")
	for _, name := range slices.Sorted(maps.Keys(object.properties)) {
		field := goFeatureIdentifier(name)
		value, err := e.typ(object.properties[name], path+field, inlinePosition)
		if err != nil {
			return "", err
		}
		tag := name
		if !node.required(name) {
			value = optionalGoField(object.properties[name], value)
			tag += ",omitzero"
		}
		fmt.Fprintf(&out, "%s %s `json:%s`\n", field, value, strconv.Quote(tag))
	}
	out.WriteString("}")
	return out.String(), nil
}

func goStruct(node *projectionNode) bool {
	return node.kind == framevalue.TypeObject && len(node.kinds) == 0 && node.object.openness == objectClosed && !node.object.patterns && canEncodeGoFields(node.object.properties)
}

// A JSON member need not fit Go's field-tag grammar. Exact maps keep such names
// instead of silently dropping or renaming data in a typed struct.
func canEncodeGoFields(properties map[string]*projectionNode) bool {
	names := make(map[string]bool, len(properties))
	for name := range properties {
		if name == "" || name == "-" || strings.ContainsAny(name, ",\\'\"`") {
			return false
		}
		field := goFeatureIdentifier(name)
		if names[field] {
			return false
		}
		names[field] = true
	}
	return true
}

func (e *featureGo) number(position typePosition) string {
	e.usesValue = true
	if position == definitionPosition {
		return "struct { " + goValueImport + ".Number }"
	}
	return goValueImport + ".Number"
}
func (e *featureGo) opaque(position typePosition) string {
	e.usesValue = true
	if position == definitionPosition {
		return "struct { " + goValueImport + ".JSON }"
	}
	return goValueImport + ".JSON"
}

// A schema reference keeps one Go representation, named by its definition.
// Method frames add no second name; a frame is named only when it is inline.
func (f *featureArtifacts) goNames(prefix string) (featureGo, error) {
	emitter := featureGo{symbols: newSymbolTable(goValueImport), names: make(map[*projectionNode]string), enums: make(map[string]goStringEnum), methods: make(map[string]string)}
	emitter.capability = emitter.symbols.claim(prefix + "CapabilityJSON")
	for _, method := range f.methods {
		name := goFeatureIdentifier(method.Name[strings.LastIndex(method.Name, "/")+1:])
		emitter.methods[method.Name] = emitter.symbols.claim(prefix + name + "Method")
	}
	for _, name := range slices.Sorted(maps.Keys(f.projection.definitions)) {
		node := f.projection.definitions[name]
		if !node.pureReference() {
			emitter.names[node] = emitter.symbols.claim(prefix + name)
		}
	}
	for _, name := range slices.Sorted(maps.Keys(f.projection.definitions)) {
		node := f.projection.definitions[name]
		if node.pureReference() {
			if _, err := emitter.namedType(node.reference); err != nil {
				return emitter, err
			}
		}
	}
	return emitter, nil
}

// Exact values have an absent zero value and decode null themselves. A pointer
// would collapse an admitted explicit null into omission before the codec runs.
func optionalGoField(node *projectionNode, expression string) string {
	for node.pureReference() {
		node = node.reference
	}
	if strings.HasPrefix(expression, "*") || len(node.kinds) > 0 || node.kind == "" || node.kind == framevalue.TypeNull || node.kind == framevalue.TypeInteger || node.kind == framevalue.TypeNumber {
		return expression
	}
	return "*" + expression
}
