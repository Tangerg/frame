package browser

import (
	jsonv1 "encoding/json"
	"fmt"
	"io"
	"maps"
	"reflect"
	"slices"
	"strings"

	"github.com/Tangerg/frame"
	"github.com/Tangerg/frame/portable/contractgen"
	framevalue "github.com/Tangerg/frame/value"
)

const (
	generatedHeader  = "// Code generated by frame/browser. DO NOT EDIT.\n\n"
	maxInlineLine    = 80
	enumValuesSuffix = "Values"
)

// WriteTypeScript projects compiled protocol types. It neither scans another
// checkout nor owns a second description of fields or enum values.
func WriteTypeScript(out io.Writer) error {
	roots := []reflect.Type{reflect.TypeFor[HTTPProblem]()}
	for _, method := range controlMethods {
		roots = append(roots, method.input)
		if method.output != nil {
			roots = append(roots, method.output)
		}
	}
	emitter, err := newTypeScriptEmitter(roots)
	if err != nil {
		return err
	}
	emitter.WriteString(generatedHeader)
	if err := emitter.writeProtocol(); err != nil {
		return err
	}
	if err := emitter.writeResponseDecoders(); err != nil {
		return err
	}
	return emitter.finish(out)
}

// WriteTypeScriptTypes projects consumer-owned DTO roots using the same emitter
// without adding their domain vocabulary to the framework control protocol.
func WriteTypeScriptTypes(out io.Writer, roots ...reflect.Type) error {
	emitter, err := newTypeScriptEmitter(roots)
	if err != nil {
		return err
	}
	emitter.WriteString(generatedHeader)
	return emitter.finish(out)
}

// typeScriptEmitter renders the named Go types reachable from its roots. Each
// TypeScript name must denote exactly one Go type.
type typeScriptEmitter struct {
	strings.Builder
	types map[string]typeScriptDeclaration
}

type typeScriptDeclaration struct {
	source reflect.Type
	model  reflect.Type
}

func newTypeScriptEmitter(roots []reflect.Type) (*typeScriptEmitter, error) {
	emitter := &typeScriptEmitter{types: make(map[string]typeScriptDeclaration)}
	for _, root := range roots {
		if err := framevalue.ValidateType(root); err != nil {
			return nil, fmt.Errorf("control: invalid wire type: %w", err)
		}
		if err := emitter.collect(root); err != nil {
			return nil, err
		}
	}
	return emitter, nil
}

func (e *typeScriptEmitter) collect(t reflect.Type) error {
	if t.Kind() == reflect.Pointer {
		return e.collect(t.Elem())
	}
	if t == reflect.TypeFor[jsonv1.Number]() {
		return nil
	}
	if existing, found := e.types[t.Name()]; found && t.PkgPath() != "" {
		if existing.source != t {
			return fmt.Errorf("control: ambiguous generated type %s", t.Name())
		}
		return nil
	}
	model, err := framevalue.EncodingModel(t)
	if err != nil {
		return fmt.Errorf("control: %w", err)
	}
	if t == model && t.Name() != "" && (t.Kind() == reflect.Slice || t.Kind() == reflect.Array || t.Kind() == reflect.Map) {
		return fmt.Errorf("control: unsupported named collection %s", t)
	}
	if t.PkgPath() != "" {
		e.types[t.Name()] = typeScriptDeclaration{source: t, model: model}
	}
	switch model.Kind() {
	case reflect.Slice, reflect.Array:
		return e.collect(model.Elem())
	case reflect.Struct:
		for _, field := range framevalue.Fields(model) {
			if err := e.collect(field.Type); err != nil {
				return err
			}
		}
	}
	return nil
}

func (e *typeScriptEmitter) render(t reflect.Type) (string, error) {
	if t.Kind() == reflect.Pointer {
		return e.render(t.Elem())
	}
	if t == reflect.TypeFor[jsonv1.Number]() {
		return `import("@frame/sdk/json").JSONNumber`, nil
	}
	if t.Name() != "" && t.PkgPath() != "" {
		return t.Name(), nil
	}
	return e.renderModel(t)
}

func (e *typeScriptEmitter) renderModel(t reflect.Type) (string, error) {
	if t == reflect.TypeFor[jsonv1.Number]() {
		return e.render(t)
	}
	switch t.Kind() {
	case reflect.Interface:
		return "unknown", nil
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Uint, reflect.Int8, reflect.Uint8, reflect.Int16, reflect.Uint16, reflect.Int32, reflect.Uint32, reflect.Int64, reflect.Uint64:
		return "number", nil
	case reflect.Slice, reflect.Array:
		element, err := e.render(t.Elem())
		if strings.HasPrefix(element, "readonly ") || strings.Contains(element, " | ") {
			element = "(" + element + ")"
		}
		return "readonly " + element + "[]", err
	default:
		return "", fmt.Errorf("control: unsupported protocol type %s", t)
	}
}

func (e *typeScriptEmitter) writeProtocol() error {
	fmt.Fprintf(e, "export const PROTOCOL = %s as const;\n\n", contractgen.TypeScriptStringLiteral(Protocol))
	fmt.Fprintf(e, "export const MAX_NAME_BYTES = %d as const;\n\n", frame.MaxNameBytes)
	fmt.Fprintf(e, "export const DIGEST_PATTERN = %s as const;\n\n", contractgen.TypeScriptStringLiteral(framevalue.DigestPattern()))
	if err := e.writeMethodMap("ControlInputs", func(method controlMethod) reflect.Type { return method.input }); err != nil {
		return err
	}
	if err := e.writeMethodMap("ControlOutputs", func(method controlMethod) reflect.Type { return method.output }); err != nil {
		return err
	}
	e.WriteString("export const CONTROL_ERROR_CODES = [\n")
	for _, problem := range controlProblems {
		fmt.Fprintf(e, "  %s,\n", contractgen.TypeScriptStringLiteral(problem.code))
	}
	e.WriteString("] as const;\n\nexport const CONTROL_MUTATIONS = [\n")
	for _, method := range controlMethods {
		if method.effect == mutates {
			fmt.Fprintf(e, "  %s,\n", contractgen.TypeScriptStringLiteral(string(method.name)))
		}
	}
	e.WriteString("] as const;\n\n")
	return nil
}

func (e *typeScriptEmitter) writeMethodMap(name string, message func(controlMethod) reflect.Type) error {
	fmt.Fprintf(e, "export interface %s {\n", name)
	for _, method := range controlMethods {
		spelling, err := e.renderMessage(message(method))
		if err != nil {
			return err
		}
		fmt.Fprintf(e, "  readonly %s: %s;\n", contractgen.PropertyKey(string(method.name)), spelling)
	}
	e.WriteString("}\n\n")
	return nil
}

func (e *typeScriptEmitter) renderMessage(t reflect.Type) (string, error) {
	switch t {
	case nil:
		return "void", nil
	case reflect.TypeFor[struct{}]():
		return "Record<string, never>", nil
	default:
		return e.render(t)
	}
}

func (e *typeScriptEmitter) finish(out io.Writer) error {
	for _, name := range slices.Sorted(maps.Keys(e.types)) {
		if err := e.writeDeclaration(name, e.types[name]); err != nil {
			return err
		}
	}
	_, err := io.WriteString(out, strings.TrimRight(e.String(), "\n")+"\n")
	return err
}

// writeEnum emits the runtime values of an enum and derives its type from
// them, so TypeScript code checks membership against the same Go-owned list.
func (e *typeScriptEmitter) writeEnum(name string, values []string) {
	quoted := contractgen.QuoteAll(values)
	list := name + enumValuesSuffix
	if declaration := fmt.Sprintf("export const %s = [%s] as const;", list, strings.Join(quoted, ", ")); len(declaration) <= maxInlineLine {
		e.WriteString(declaration + "\n")
	} else {
		fmt.Fprintf(e, "export const %s = [\n  %s,\n] as const;\n", list, strings.Join(quoted, ",\n  "))
	}
	if declaration := fmt.Sprintf("export type %s = (typeof %s)[number];", name, list); len(declaration) <= maxInlineLine {
		e.WriteString(declaration + "\n\n")
	} else {
		fmt.Fprintf(e, "export type %s =\n  (typeof %s)[number];\n\n", name, list)
	}
}

func (e *typeScriptEmitter) writeDeclaration(name string, declaration typeScriptDeclaration) error {
	if values, ok := reflect.Zero(declaration.source).Interface().(interface{ Values() []string }); ok {
		if declaration.model.Kind() != reflect.String || declaration.model == reflect.TypeFor[jsonv1.Number]() {
			return fmt.Errorf("control: string enum %s requires a string encoding model", declaration.source)
		}
		e.writeEnum(name, values.Values())
		return nil
	}
	t := declaration.model
	if t.Kind() != reflect.Struct {
		spelling, err := e.renderModel(t)
		if err != nil {
			return err
		}
		if t.Kind() == reflect.Interface && !framevalue.AllowsNull(declaration.source) {
			spelling = "{}"
		}
		fmt.Fprintf(e, "export type %s = %s;\n\n", name, spelling)
		return nil
	}
	fmt.Fprintf(e, "export interface %s {\n", name)
	for _, field := range framevalue.Fields(t) {
		spelling, err := e.render(field.Type)
		if err != nil {
			return err
		}
		marker := ""
		if field.Optional {
			marker = "?"
		}
		fmt.Fprintf(e, "  readonly %s%s: %s;\n", contractgen.PropertyKey(field.Name), marker, spelling)
	}
	e.WriteString("}\n\n")
	return nil
}
