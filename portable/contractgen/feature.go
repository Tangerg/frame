package contractgen

import (
	"encoding/json/jsontext"
	json "encoding/json/v2"
	"fmt"
	"go/token"
	"maps"
	"net/url"
	"slices"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/Tangerg/frame/portable"
	framevalue "github.com/Tangerg/frame/value"
)

type featureMethod struct {
	Name        string              `json:"name"`
	Kind        portable.MethodKind `json:"kind"`
	Target      string              `json:"target"`
	Description string              `json:"description"`
	Input       string              `json:"input"`
	Output      string              `json:"output"`
	Stream      string              `json:"stream,omitempty"`
}

type featureArtifacts struct {
	definitions map[string]jsontext.Value
	methods     []featureMethod
	typescript  string
	capability  *portable.Capability
	projection  *projection
}

func buildFeature(data []byte) (*featureArtifacts, error) {
	contract, err := portable.ParseCapability(data)
	if err != nil {
		return nil, err
	}
	descriptor := contract.Descriptor()
	descriptors := descriptor.Methods
	artifacts := &featureArtifacts{definitions: make(map[string]jsontext.Value), capability: contract}

	roots, renamed, err := featureNames(descriptors)
	if err != nil {
		return nil, err
	}
	for _, descriptor := range descriptors {
		if descriptor.Description == "" || !utf8.ValidString(descriptor.Description) {
			return nil, fmt.Errorf("feature contracts: method description is required for %q", descriptor.Name)
		}
		root := roots[descriptor.Name]
		method := featureMethod{Name: descriptor.Name, Kind: descriptor.Kind, Target: descriptor.Target, Description: descriptor.Description, Input: "schema.json" + RefPrefix + root + "Input", Output: "schema.json" + RefPrefix + root + "Output"}
		if len(descriptor.Stream) != 0 {
			method.Stream = "schema.json" + RefPrefix + root + "Chunk"
			if err := addFeatureSchema(artifacts, root+"Chunk", descriptor.Stream, renamed); err != nil {
				return nil, err
			}
		}
		for _, frame := range []struct {
			name string
			raw  jsontext.Value
		}{{root + "Input", descriptor.Input}, {root + "Output", descriptor.Output}} {
			if err := addFeatureSchema(artifacts, frame.name, frame.raw, renamed); err != nil {
				return nil, err
			}
		}
		artifacts.methods = append(artifacts.methods, method)
	}
	graph, err := newProjection(artifacts.definitions)
	if err != nil {
		return nil, err
	}
	artifacts.projection = graph
	definitions := graph.definitions
	emitter := &typeScript{graph: graph}
	var output strings.Builder
	line := func(format string, values ...any) { fmt.Fprintf(&output, format+"\n", values...) }
	line("// Code generated by Frame contractgen from the published capability descriptor. DO NOT EDIT.")
	line("// Numeric and cross-field constraints remain in schema.json and the business owner.")
	if slices.ContainsFunc(slices.Collect(maps.Values(definitions)), func(node *projectionNode) bool {
		return strings.Contains(emitter.TypeOf(node), "JSONNumber")
	}) {
		line("import type { JSONNumber } from \"@frame/sdk/json\";")
	}
	line("")
	for _, name := range slices.Sorted(maps.Keys(definitions)) {
		output.WriteString(emitter.Definition(name, definitions[name]))
	}
	line("export interface MethodInputs {")
	for _, method := range artifacts.methods {
		line("  %s: %s;", TypeScriptStringLiteral(method.Name), strings.TrimPrefix(method.Input, "schema.json"+RefPrefix))
	}
	line("}")
	line("export interface MethodOutputs {")
	for _, method := range artifacts.methods {
		line("  %s: %s;", TypeScriptStringLiteral(method.Name), strings.TrimPrefix(method.Output, "schema.json"+RefPrefix))
	}
	line("}")
	if slices.ContainsFunc(artifacts.methods, func(method featureMethod) bool { return method.Stream != "" }) {
		line("export interface MethodChunks {")
		for _, method := range artifacts.methods {
			if method.Stream != "" {
				line("  %s: %s;", TypeScriptStringLiteral(method.Name), strings.TrimPrefix(method.Stream, "schema.json"+RefPrefix))
			}
		}
		line("}")
	}
	line("export const METHODS = {")
	for _, method := range artifacts.methods {
		stream := ""
		if method.Stream != "" {
			stream = ", streaming: true"
		}
		line("  %s: { kind: %s, target: %s%s },", TypeScriptStringLiteral(method.Name), TypeScriptStringLiteral(string(method.Kind)), TypeScriptStringLiteral(method.Target), stream)
	}
	line("} as const;")
	line("export const CAPABILITY = { protocol: %s, reference: %s, contract: %s } as const;", TypeScriptStringLiteral(descriptor.Protocol), TypeScriptStringLiteral(descriptor.Reference), TypeScriptStringLiteral(contract.Identity().Digest().String()))
	line("export const CAPABILITY_JSON = %s;", TypeScriptStringLiteral(string(contract.Identity().Bytes())))
	artifacts.typescript = output.String()
	return artifacts, nil
}

func sharedDefinitions(descriptors []portable.MethodDescriptor) (map[string]jsontext.Value, error) {
	keys := make(map[string]jsontext.Value)
	for _, descriptor := range descriptors {
		for _, raw := range []jsontext.Value{descriptor.Input, descriptor.Output, descriptor.Stream} {
			if len(raw) == 0 || raw.Kind() == 't' || raw.Kind() == 'f' {
				continue
			}
			var document struct {
				Defs map[string]jsontext.Value `json:"$defs"`
			}
			if err := json.Unmarshal(raw, &document); err != nil {
				return nil, err
			}
			for key, body := range document.Defs {
				canonical, err := framevalue.ParseJSON(body)
				if err != nil {
					return nil, err
				}
				if known, found := keys[key]; found && string(known) != canonical.String() {
					return nil, fmt.Errorf("feature contracts: methods publish different %s definitions", key)
				}
				keys[key] = canonical.Bytes()
			}
		}
	}
	return keys, nil
}

func featureNames(descriptors []portable.MethodDescriptor) (map[string]string, map[string]string, error) {
	roots := make(map[string]string, len(descriptors))
	owners := make(map[string]string)
	claim := func(name, owner string) error {
		if !token.IsIdentifier(name) {
			return fmt.Errorf("feature contracts: %q has no identifier name", owner)
		}
		if previous, taken := owners[name]; taken && previous != owner {
			return fmt.Errorf("feature contracts: %q and %q both name %s", previous, owner, name)
		}
		owners[name] = owner
		return nil
	}
	for _, descriptor := range descriptors {
		root := goFeatureIdentifier(descriptor.Name[strings.LastIndex(descriptor.Name, "/")+1:])
		for _, suffix := range []string{"Input", "Output", "Chunk"} {
			if err := claim(root+suffix, descriptor.Name); err != nil {
				return nil, nil, err
			}
		}
		roots[descriptor.Name] = root
	}
	keys, err := sharedDefinitions(descriptors)
	if err != nil {
		return nil, nil, err
	}
	// A contract names a definition <package>.<type>; a projection drops the
	// package unless another definition shares the type name.
	typeName := func(key string) string { return key[strings.IndexByte(key, '.')+1:] }
	sharing := make(map[string]int, len(keys))
	for key := range keys {
		sharing[typeName(key)]++
	}
	renamed := make(map[string]string, len(keys))
	for _, key := range slices.Sorted(maps.Keys(keys)) {
		name := goFeatureIdentifier(typeName(key))
		if sharing[typeName(key)] > 1 {
			name = goFeatureIdentifier(key)
		}
		if err := claim(name, key); err != nil {
			return nil, nil, err
		}
		renamed[key] = name
	}
	// An exported type that encodes itself through an unexported one publishes
	// that encoding under its own name; the reference between them disappears.
	encodedBy := make(map[string][]string)
	for key, body := range keys {
		var reference struct {
			Ref string `json:"$ref"`
		}
		if json.Unmarshal(body, &reference) == nil && reference.Ref != "" {
			if target, local := strings.CutPrefix(reference.Ref, RefPrefix); local {
				encodedBy[target] = append(encodedBy[target], key)
			}
		}
	}
	for target, encoders := range encodedBy {
		initial, _ := utf8.DecodeRuneInString(typeName(target))
		if len(encoders) == 1 && keys[target] != nil && unicode.IsLower(initial) {
			renamed[target] = renamed[encoders[0]]
		}
	}
	return roots, renamed, nil
}

func addFeatureSchema(artifacts *featureArtifacts, root string, raw jsontext.Value, renamed map[string]string) error {
	canonical, err := framevalue.ParseJSON(raw)
	if err != nil {
		return err
	}
	raw = canonical.Bytes()
	if raw.Kind() == 't' || raw.Kind() == 'f' {
		artifacts.definitions[root] = raw
		return nil
	}
	var document map[string]jsontext.Value
	if err := json.Unmarshal(raw, &document); err != nil {
		return err
	}
	var definitions map[string]jsontext.Value
	if defs := document["$defs"]; len(defs) != 0 {
		if err := json.Unmarshal(defs, &definitions); err != nil {
			return err
		}
	}
	delete(document, "$defs")
	delete(document, "$schema")
	for name, body := range definitions {
		updated, err := rewriteFeatureRefs(body, renamed, root)
		if err != nil {
			return err
		}
		if string(updated) == `{"$ref":"`+RefPrefix+renamed[name]+`"}` {
			continue
		}
		if previous, exists := artifacts.definitions[renamed[name]]; exists && string(previous) != string(updated) {
			return fmt.Errorf("feature contracts: definition %q has competing schemas", name)
		}
		artifacts.definitions[renamed[name]] = updated
	}
	body, err := json.Marshal(document, json.Deterministic(true))
	if err != nil {
		return err
	}
	updated, err := rewriteFeatureRefs(body, renamed, root)
	if err != nil {
		return err
	}
	// Scope expands the root while retaining its named definition. Publish one
	// data shape when that definition is unambiguous; method identities remain distinct.
	var matching []string
	for name := range definitions {
		if string(artifacts.definitions[renamed[name]]) == string(updated) {
			matching = append(matching, renamed[name])
		}
	}
	if len(matching) == 1 {
		updated, err = json.Marshal(map[string]string{"$ref": RefPrefix + matching[0]})
		if err != nil {
			return err
		}
	}
	artifacts.definitions[root] = updated
	return nil
}

func rewriteFeatureRefs(raw jsontext.Value, renamed map[string]string, root string) (jsontext.Value, error) {
	if string(raw) == "true" || string(raw) == "false" {
		return raw, nil
	}
	var node map[string]jsontext.Value
	if err := json.Unmarshal(raw, &node); err != nil {
		return nil, err
	}
	if reference := node["$ref"]; len(reference) != 0 {
		var ref string
		if err := json.Unmarshal(reference, &ref); err != nil {
			return nil, err
		}
		path, err := referencePath(ref)
		if err != nil {
			return nil, err
		}
		tokens, err := pointerTokens(path)
		if err != nil {
			return nil, err
		}
		target := []string{"$defs", root}
		if len(tokens) >= 2 && tokens[0] == "$defs" {
			name := renamed[tokens[1]]
			if name == "" {
				return nil, fmt.Errorf("feature contracts: unknown definition %q", tokens[1])
			}
			target = []string{"$defs", name}
			tokens = tokens[2:]
		}
		target = append(target, tokens...)
		for i, token := range target {
			target[i] = pointerToken(token)
		}
		fragment := url.URL{Fragment: "/" + strings.Join(target, "/")}
		encoded, err := json.Marshal(fragment.String())
		if err != nil {
			return nil, err
		}
		node["$ref"] = encoded
	}
	for _, key := range []string{"properties", "patternProperties", "dependentSchemas", "$defs", "definitions"} {
		if len(node[key]) == 0 {
			continue
		}
		var children map[string]jsontext.Value
		if err := json.Unmarshal(node[key], &children); err != nil {
			return nil, err
		}
		for name, child := range children {
			updated, err := rewriteFeatureRefs(child, renamed, root)
			if err != nil {
				return nil, err
			}
			children[name] = updated
		}
		encoded, err := json.Marshal(children, json.Deterministic(true))
		if err != nil {
			return nil, err
		}
		node[key] = encoded
	}
	for _, key := range []string{"allOf", "anyOf", "oneOf", "prefixItems"} {
		if len(node[key]) == 0 {
			continue
		}
		var children []jsontext.Value
		if err := json.Unmarshal(node[key], &children); err != nil {
			return nil, err
		}
		for index, child := range children {
			updated, err := rewriteFeatureRefs(child, renamed, root)
			if err != nil {
				return nil, err
			}
			children[index] = updated
		}
		encoded, err := json.Marshal(children)
		if err != nil {
			return nil, err
		}
		node[key] = encoded
	}
	for _, key := range []string{"items", "additionalProperties", "unevaluatedProperties", "propertyNames", "contains", "not", "if", "then", "else"} {
		if len(node[key]) == 0 {
			continue
		}
		updated, err := rewriteFeatureRefs(node[key], renamed, root)
		if err != nil {
			return nil, err
		}
		node[key] = updated
	}
	return json.Marshal(node, json.Deterministic(true))
}

func (f *featureArtifacts) schemaJSON() ([]byte, error) {
	return encodeFeature(struct {
		Schema string                    `json:"$schema"`
		Defs   map[string]jsontext.Value `json:"$defs"`
	}{SchemaDialect, f.definitions})
}

func (f *featureArtifacts) methodsJSON() ([]byte, error) { return encodeFeature(f.methods) }
func (f *featureArtifacts) capabilityJSON() ([]byte, error) {
	return encodeFeature(f.capability.Descriptor())
}
func (f *featureArtifacts) typeScript() string { return f.typescript }

func (f *featureArtifacts) reference() string {
	var reference strings.Builder
	reference.WriteString("# Feature operations\n\nGenerated from the feature's Go-owned method contracts.\n\n| Method | Kind | Target | Description |\n| --- | --- | --- | --- |\n")
	for _, method := range f.methods {
		description := strings.NewReplacer("|", "\\|", "\n", " ", "\r", " ").Replace(method.Description)
		if method.Stream != "" {
			description += " Stream chunks: " + method.Stream + "; final result: " + method.Output + "."
		}
		fmt.Fprintf(&reference, "| `%s` | %s | %s | %s |\n", method.Name, method.Kind, method.Target, description)
	}
	descriptor := f.capability.Descriptor()
	fmt.Fprintf(&reference, "\nCapability `%s` exposes the declared methods. Required backend protocol: `%s`.\n\n`capability.generated.json` preserves the canonical callable contract; `schema.json` and the method references are presentation projections.\n", descriptor.Reference, descriptor.Protocol)
	return reference.String()
}

func encodeFeature(value any) ([]byte, error) {
	data, err := json.Marshal(value, jsontext.WithIndent("  "), json.Deterministic(true))
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}
