type featureMethod struct {
	Name        string           `json:"name"`
	Kind        frame.MethodKind `json:"kind"`
	Target      string           `json:"target"`
	Description string           `json:"description"`
	Input       string           `json:"input"`
	Output      string           `json:"output"`
	Stream      string           `json:"stream,omitempty"`
}

type featureArtifacts struct {
	definitions map[string]jsontext.Value
	stringEnums map[string][]string
	methods     []featureMethod
	typescript  string
	capability  *frame.Capability
	projection  *projection
}

// schemaFile is the published JSON Schema document that method references
// address.
const schemaFile = "schema.json"

func schemaReference(definition string) string { return schemaFile + RefPrefix + definition }

// methodFrame is one schema position of a method. Its suffix qualifies the
// method's root symbol, so the frames of one method claim names as a family.
type methodFrame string

const (
	frameInput  methodFrame = "Input"
	frameOutput methodFrame = "Output"
	frameChunk  methodFrame = "Chunk"
)

var methodFrames = []methodFrame{frameInput, frameOutput, frameChunk}

func (f methodFrame) definition(root string) string { return root + string(f) }

// schema returns the frame's schema; an absent chunk schema is empty.
func (f methodFrame) schema(descriptor frame.MethodDescriptor) jsontext.Value {
	switch f {
	case frameInput:
		return descriptor.Input
	case frameOutput:
		return descriptor.Output
	default:
		return descriptor.Stream
	}
}

// Local definition names identify nodes only within their original method frame.
// Equal spellings or bodies cannot establish identity across reference scopes.
type schemaDefinition struct {
	root string
	name string
}

func (d schemaDefinition) compare(other schemaDefinition) int {
	if order := strings.Compare(d.root, other.root); order != 0 {
		return order
	}
	return strings.Compare(d.name, other.name)
}

func buildFeature(data []byte) (*featureArtifacts, error) {
	contract, err := frame.ParseCapability(data)
	if err != nil {
		return nil, fmt.Errorf("%w: capability: %w", ErrInvalid, err)
	}
	descriptors := contract.Descriptor().Methods
	artifacts := &featureArtifacts{definitions: make(map[string]jsontext.Value), stringEnums: make(map[string][]string), capability: contract}
	roots, renamed, err := featureNames(descriptors)
	if err != nil {
		return nil, err
	}
	for _, descriptor := range descriptors {
		root := roots[descriptor.Name]
		method := featureMethod{Name: descriptor.Name, Kind: descriptor.Kind, Target: descriptor.Target, Description: descriptor.Description, Input: schemaReference(frameInput.definition(root)), Output: schemaReference(frameOutput.definition(root))}
		if len(descriptor.Stream) != 0 {
			method.Stream = schemaReference(frameChunk.definition(root))
		}
		for _, frame := range methodFrames {
			if raw := frame.schema(descriptor); len(raw) != 0 {
				if err := addFeatureSchema(artifacts, frame.definition(root), raw, renamed); err != nil {
					return nil, err
				}
			}
		}
		artifacts.methods = append(artifacts.methods, method)
	}
	artifacts.projection, err = newProjection(artifacts.definitions)
	if err != nil {
		return nil, err
	}
	for pointer, members := range artifacts.stringEnums {
		node := artifacts.projection.paths[pointer]
		if node == nil {
			return nil, fmt.Errorf("feature contracts: enum schema missing at %q", pointer)
		}
		node.stringValues = members
	}
	artifacts.typescript = artifacts.renderTypeScript()
	return artifacts, nil
}

func (f *featureArtifacts) renderTypeScript() string {
	definitions := f.projection.definitions
	emitter := newTypeScript(f.projection)
	var declarations strings.Builder
	for _, name := range slices.Sorted(maps.Keys(definitions)) {
		declarations.WriteString(emitter.Definition(emitter.names[definitions[name]], definitions[name]))
	}
	var output strings.Builder
	line := func(format string, values ...any) { fmt.Fprintf(&output, format+"\n", values...) }
	line("// Code generated by Frame contractgen from the published capability descriptor. DO NOT EDIT.")
	line("// Numeric and cross-field constraints remain in schema.json and the business owner.")
	if emitter.usesNumber {
		line("import type { %s } from \"@frame/sdk/json\";", typeScriptNumber)
	}
	line("")
	output.WriteString(declarations.String())
	typeName := func(reference string) string {
		return emitter.names[definitions[strings.TrimPrefix(reference, schemaReference(""))]]
	}
	line("export interface %s {", methodInputs)
	for _, method := range f.methods {
		line("  %s: %s;", TypeScriptStringLiteral(method.Name), typeName(method.Input))
	}
	line("}")
	line("export interface %s {", methodOutputs)
	for _, method := range f.methods {
		line("  %s: %s;", TypeScriptStringLiteral(method.Name), typeName(method.Output))
	}
	line("}")
	if slices.ContainsFunc(f.methods, func(method featureMethod) bool { return method.Stream != "" }) {
		line("export interface %s {", methodChunks)
		for _, method := range f.methods {
			if method.Stream != "" {
				line("  %s: %s;", TypeScriptStringLiteral(method.Name), typeName(method.Stream))
			}
		}
		line("}")
	}
	line("export const %s = {", methodsConstant)
	for _, method := range f.methods {
		stream := ""
		if method.Stream != "" {
			stream = ", streaming: true"
		}
		line("  %s: { kind: %s, target: %s%s },", RuntimePropertyKey(method.Name), TypeScriptStringLiteral(string(method.Kind)), TypeScriptStringLiteral(method.Target), stream)
	}
	line("} as const;")
	descriptor := f.capability.Descriptor()
	identity := f.capability.Identity()
	line("export const %s = { protocol: %s, reference: %s, contract: %s } as const;", capabilityConstant, TypeScriptStringLiteral(descriptor.Protocol), TypeScriptStringLiteral(descriptor.Reference), TypeScriptStringLiteral(identity.Digest().String()))
	line("export const %s = %s;", capabilityJSONConstant, TypeScriptStringLiteral(string(identity.Bytes())))
	return output.String()
}

func scopedDefinitions(descriptors []frame.MethodDescriptor, roots map[string]string) (map[schemaDefinition]jsontext.Value, error) {
	definitions := make(map[schemaDefinition]jsontext.Value)
	for _, descriptor := range descriptors {
		root := roots[descriptor.Name]
		for _, frame := range methodFrames {
			raw := frame.schema(descriptor)
			if len(raw) == 0 || raw.Kind() == 't' || raw.Kind() == 'f' {
				continue
			}
			var document struct {
				Defs map[string]jsontext.Value `json:"$defs"`
			}
			if err := json.Unmarshal(raw, &document); err != nil {
				return nil, err
			}
			for name, body := range document.Defs {
				canonical, err := framevalue.ParseJSON(body)
				if err != nil {
					return nil, err
				}
				definitions[schemaDefinition{root: frame.definition(root), name: name}] = canonical.Bytes()
			}
		}
	}
	return definitions, nil
}

func featureNames(descriptors []frame.MethodDescriptor) (map[string]string, map[schemaDefinition]string, error) {
	roots := make(map[string]string, len(descriptors))
	suffixes := make([]string, len(methodFrames))
	for i, frame := range methodFrames {
		suffixes[i] = string(frame)
	}
	symbols := newSymbolTable()
	descriptors = slices.Clone(descriptors)
	slices.SortFunc(descriptors, func(left, right frame.MethodDescriptor) int { return strings.Compare(left.Name, right.Name) })
	for _, descriptor := range descriptors {
		root := goFeatureIdentifier(descriptor.Name[strings.LastIndex(descriptor.Name, "/")+1:])
		roots[descriptor.Name] = symbols.claimFamily(root, suffixes...)
	}
	keys, err := scopedDefinitions(descriptors, roots)
	if err != nil {
		return nil, nil, err
	}
	owners, err := definitionOwners(keys)
	if err != nil {
		return nil, nil, err
	}
	typeName := func(key string) string { return key[strings.IndexByte(key, '.')+1:] }
	sharing := make(map[string]int, len(keys))
	qualified := make(map[string]int, len(keys))
	for key, owner := range owners {
		if owner == key {
			sharing[typeName(key.name)]++
			qualified[key.name]++
		}
	}
	renamed := make(map[schemaDefinition]string, len(keys))
	for _, key := range slices.SortedFunc(maps.Keys(keys), schemaDefinition.compare) {
		if owners[key] != key {
			continue
		}
		name := goFeatureIdentifier(typeName(key.name))
		if sharing[typeName(key.name)] > 1 {
			name = goFeatureIdentifier(key.name)
		}
		if qualified[key.name] > 1 {
			name = key.root + name
		}
		renamed[key] = symbols.claim(name)
	}
	for key, owner := range owners {
		renamed[key] = renamed[owner]
	}
	return roots, renamed, nil
}

// An unexported encoding with one referring definition belongs to that
// definition's ultimate owner. Resolve ownership before allocating symbols so
// an intermediate alias cannot acquire a name through map iteration order.
func definitionOwners(definitions map[schemaDefinition]jsontext.Value) (map[schemaDefinition]schemaDefinition, error) {
	encodedBy := make(map[schemaDefinition][]schemaDefinition)
	for key, body := range definitions {
		name, referenced, err := pureDefinitionReference(body)
		if err != nil {
			return nil, err
		}
		if referenced {
			target := schemaDefinition{root: key.root, name: name}
			encodedBy[target] = append(encodedBy[target], key)
		}
	}
	parents := make(map[schemaDefinition]schemaDefinition)
	for target, encoders := range encodedBy {
		initial, _ := utf8.DecodeRuneInString(target.name[strings.IndexByte(target.name, '.')+1:])
		if len(encoders) == 1 && definitions[target] != nil && unicode.IsLower(initial) {
			parents[target] = encoders[0]
		}
	}
	owners := make(map[schemaDefinition]schemaDefinition, len(definitions))
	active := make(map[schemaDefinition]bool)
	var resolve func(schemaDefinition) (schemaDefinition, error)
	resolve = func(key schemaDefinition) (schemaDefinition, error) {
		if owner, resolved := owners[key]; resolved {
			return owner, nil
		}
		if active[key] {
			return schemaDefinition{}, fmt.Errorf("feature contracts: definition ownership cycle at %q in %s", key.name, key.root)
		}
		active[key] = true
		owner := key
		if parent, exists := parents[key]; exists {
			var err error
			owner, err = resolve(parent)
			if err != nil {
				return schemaDefinition{}, err
			}
		}
		delete(active, key)
		owners[key] = owner
		return owner, nil
	}
	for _, key := range slices.SortedFunc(maps.Keys(definitions), schemaDefinition.compare) {
		if _, err := resolve(key); err != nil {
			return nil, err
		}
	}
	return owners, nil
}

func pureDefinitionReference(raw jsontext.Value) (string, bool, error) {
	if raw.Kind() != '{' {
		return "", false, nil
	}
	var schema map[string]jsontext.Value
	if err := json.Unmarshal(raw, &schema); err != nil {
		return "", false, err
	}
	if len(schema) != 1 || len(schema[framevalue.KeywordRef]) == 0 {
		return "", false, nil
	}
	var ref string
	if err := json.Unmarshal(schema[framevalue.KeywordRef], &ref); err != nil {
		return "", false, err
	}
	path, err := referencePath(ref)
	if err != nil {
		return "", false, err
	}
	tokens, err := pointerTokens(path)
	if err != nil {
		return "", false, err
	}
	if len(tokens) == 2 && tokens[0] == framevalue.KeywordDefs {
		return tokens[1], true, nil
	}
	return "", false, nil
}

func addFeatureSchema(artifacts *featureArtifacts, root string, raw jsontext.Value, names map[schemaDefinition]string) error {
	canonical, err := framevalue.ParseJSON(raw)
	if err != nil {
		return err
	}
	raw = canonical.Bytes()
	if raw.Kind() == 't' || raw.Kind() == 'f' {
		artifacts.definitions[root] = raw
		return nil
	}
	enumerations, err := framevalue.ProjectStringEnums(raw)
	if err != nil {
		return err
	}
	document, definitions, err := detachDefinitions(raw)
	if err != nil {
		return err
	}
	renamed := make(map[string]string, len(definitions))
	for name := range definitions {
		renamed[name] = names[schemaDefinition{root: root, name: name}]
	}
	projected, err := projectFeatureDefinitions(definitions, renamed, root)
	if err != nil {
		return err
	}
	body, err := json.Marshal(document, json.Deterministic(true))
	if err != nil {
		return err
	}
	updated, err := rewriteFeatureRefs(body, renamed, root)
	if err != nil {
		return err
	}
	// An expanded root can share its named definition only if references to its
	// original descendants move with it. A $ref is not a JSON Pointer path alias.
	var matching []string
	for name, body := range projected {
		if string(body) == string(updated) {
			matching = append(matching, name)
		}
	}
	owner := root
	if len(matching) == 1 {
		owner = matching[0]
		projected, err = projectFeatureDefinitions(definitions, renamed, matching[0])
		if err != nil {
			return err
		}
		updated, err = json.Marshal(map[string]string{framevalue.KeywordRef: RefPrefix + matching[0]})
		if err != nil {
			return err
		}
	}
	for _, enumeration := range enumerations {
		pointer, err := projectFeaturePointer(enumeration.Pointer, renamed, owner)
		if err != nil {
			return err
		}
		if previous, exists := artifacts.stringEnums[pointer]; exists && !slices.Equal(previous, enumeration.Values) {
			return fmt.Errorf("feature contracts: enum schema %q has competing projections", pointer)
		}
		artifacts.stringEnums[pointer] = enumeration.Values
	}
	for name, body := range projected {
		if previous, exists := artifacts.definitions[name]; exists && string(previous) != string(body) {
			return fmt.Errorf("feature contracts: definition %q has competing schemas", name)
		}
		artifacts.definitions[name] = body
	}
	artifacts.definitions[root] = updated
	return nil
}

// detachDefinitions splits a schema object into its body and its local
// definitions. The dialect declaration is dropped because schema.json owns it.
func detachDefinitions(raw jsontext.Value) (map[string]jsontext.Value, map[string]jsontext.Value, error) {
	var document map[string]jsontext.Value
	if err := json.Unmarshal(raw, &document); err != nil {
		return nil, nil, err
	}
	var definitions map[string]jsontext.Value
	if defs := document[framevalue.KeywordDefs]; len(defs) != 0 {
		if err := json.Unmarshal(defs, &definitions); err != nil {
			return nil, nil, err
		}
	}
	delete(document, framevalue.KeywordDefs)
	delete(document, framevalue.KeywordSchema)
	return document, definitions, nil
}

func projectFeatureDefinitions(definitions map[string]jsontext.Value, renamed map[string]string, root string) (map[string]jsontext.Value, error) {
	projected := make(map[string]jsontext.Value, len(definitions))
	for name, body := range definitions {
		updated, err := rewriteFeatureRefs(body, renamed, root)
		if err != nil {
			return nil, err
		}
		target := renamed[name]
		if string(updated) == `{"$ref":"`+RefPrefix+target+`"}` {
			continue
		}
		if previous, exists := projected[target]; exists && string(previous) != string(updated) {
			return nil, fmt.Errorf("feature contracts: definition %q has competing schemas", name)
		}
		projected[target] = updated
	}
	return projected, nil
}

func rewriteFeatureRefs(raw jsontext.Value, renamed map[string]string, root string) (jsontext.Value, error) {
	return rewriteFeatureSchema(raw, renamed, root, framevalue.ProfileSchema())
}

func rewriteFeatureSchema(raw jsontext.Value, renamed map[string]string, root string, profile framevalue.SchemaProfile) (jsontext.Value, error) {
	if string(raw) == jsonTrue || string(raw) == jsonFalse {
		return raw, nil
	}
	var node map[string]jsontext.Value
	if err := json.Unmarshal(raw, &node); err != nil {
		return nil, err
	}
	if reference := node[framevalue.KeywordRef]; len(reference) != 0 {
		var ref string
		if err := json.Unmarshal(reference, &ref); err != nil {
			return nil, err
		}
		path, err := referencePath(ref)
		if err != nil {
			return nil, err
		}
		pointer, err := projectFeaturePointer(path, renamed, root)
		if err != nil {
			return nil, err
		}
		fragment := url.URL{Fragment: pointer}
		encoded, err := json.Marshal(fragment.String())
		if err != nil {
			return nil, err
		}
		node[framevalue.KeywordRef] = encoded
	}
	for key, child := range node {
		updated, err := rewriteFeatureChildren(child, profile.Keywords[key].Children, renamed, root, profile)
		if err != nil {
			return nil, err
		}
		node[key] = updated
	}
	return json.Marshal(node, json.Deterministic(true))
}

func projectFeaturePointer(pointer string, renamed map[string]string, root string) (string, error) {
	tokens, err := pointerTokens(pointer)
	if err != nil {
		return "", err
	}
	target := []string{framevalue.KeywordDefs, root}
	if len(tokens) >= 2 && tokens[0] == framevalue.KeywordDefs {
		name := renamed[tokens[1]]
		if name == "" {
			return "", fmt.Errorf("feature contracts: unknown definition %q", tokens[1])
		}
		target = []string{framevalue.KeywordDefs, name}
		tokens = tokens[2:]
	}
	target = append(target, tokens...)
	for i, token := range target {
		target[i] = pointerToken(token)
	}
	return "/" + strings.Join(target, "/"), nil
}

func rewriteFeatureChildren(raw jsontext.Value, children framevalue.SchemaChildren, renamed map[string]string, root string, profile framevalue.SchemaProfile) (jsontext.Value, error) {
	switch children {
	case framevalue.SchemaMap:
		var values map[string]jsontext.Value
		if err := json.Unmarshal(raw, &values); err != nil {
			return nil, err
		}
		for name, child := range values {
			updated, err := rewriteFeatureSchema(child, renamed, root, profile)
			if err != nil {
				return nil, err
			}
			values[name] = updated
		}
		return json.Marshal(values, json.Deterministic(true))
	case framevalue.SchemaArray:
		var values []jsontext.Value
		if err := json.Unmarshal(raw, &values); err != nil {
			return nil, err
		}
		for index, child := range values {
			updated, err := rewriteFeatureSchema(child, renamed, root, profile)
			if err != nil {
				return nil, err
			}
			values[index] = updated
		}
		return json.Marshal(values)
	case framevalue.SchemaChild:
		return rewriteFeatureSchema(raw, renamed, root, profile)
	default:
		return raw, nil
	}
}

func (f *featureArtifacts) schemaJSON() ([]byte, error) {
	return encodeFeature(struct {
		Schema string                    `json:"$schema"`
		Defs   map[string]jsontext.Value `json:"$defs"`
	}{framevalue.SchemaDialect, f.definitions})
}

func (f *featureArtifacts) methodsJSON() ([]byte, error) { return encodeFeature(f.methods) }
func (f *featureArtifacts) capabilityJSON() ([]byte, error) {
	return encodeFeature(f.capability.Descriptor())
}
func (f *featureArtifacts) typeScript() string { return f.typescript }

func (f *featureArtifacts) reference() string {
	var reference strings.Builder
	reference.WriteString("# Feature operations\n\nGenerated from the feature's Go-owned method contracts.\n\n| Method | Kind | Target | Description |\n| --- | --- | --- | --- |\n")
	for _, method := range f.methods {
		description := strings.NewReplacer("|", "\\|", "\n", " ", "\r", " ").Replace(method.Description)
		if method.Stream != "" {
			description += " Stream chunks: " + method.Stream + "; final result: " + method.Output + "."
		}
		fmt.Fprintf(&reference, "| `%s` | %s | %s | %s |\n", method.Name, method.Kind, method.Target, description)
	}
	descriptor := f.capability.Descriptor()
	fmt.Fprintf(&reference, "\nCapability `%s` exposes the declared methods. Required backend protocol: `%s`.\n\n`capability.generated.json` preserves the canonical callable contract; `schema.json` and the method references are presentation projections.\n", descriptor.Reference, descriptor.Protocol)
	return reference.String()
}

func encodeFeature(value any) ([]byte, error) {
	data, err := json.Marshal(value, jsontext.WithIndent("  "), json.Deterministic(true))
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}
